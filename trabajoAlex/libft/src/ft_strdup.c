#include "./libft.h"

char	*ft_strdup(const char *s1)
{
	char	*copy;

	copy = (char *)malloc(sizeof(char) * (ft_strlen(s1) + 1));
	if (!copy)
		return (0);
	ft_memcpy(copy, s1, (ft_strlen(s1) + 1));
	return (copy);
}
